-- v8 批A：订单明细 + 状态推导
-- 1. 订单明细表
-- 2. 订单去掉 pay_date（回款日期改由收款流水推导，避免两处存同一个事实）
-- 3. 报价单补 opp_id（报价可挂在商机下，确认后转订单）
-- 4. 给历史订单补明细，保证金额与明细自洽
-- ============================================================
USE crm;

-- ---------- 1. 订单明细 ----------
CREATE TABLE crm_order_item (
  id           BIGINT        NOT NULL AUTO_INCREMENT,
  order_id     BIGINT        NOT NULL,
  product_id   BIGINT        DEFAULT NULL,
  product_name VARCHAR(100)  NOT NULL,
  spec         VARCHAR(100) DEFAULT NULL COMMENT '规格快照',
  unit         VARCHAR(20)  DEFAULT NULL COMMENT '单位快照',
  qty          INT           NOT NULL DEFAULT 1,
  price        DECIMAL(14,2) NOT NULL DEFAULT 0 COMMENT '成交单价',
  cost         DECIMAL(14,2) NOT NULL DEFAULT 0 COMMENT '成本快照，算毛利用',
  amount       DECIMAL(14,2) NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  KEY idx_order (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='订单明细';

-- ---------- 2. 订单去掉重复的回款日期 ----------
ALTER TABLE crm_order DROP COLUMN pay_date;

-- ---------- 3. 报价单挂商机 ----------
ALTER TABLE crm_quotation
  ADD COLUMN opp_id BIGINT DEFAULT NULL COMMENT '来源商机ID' AFTER customer_id;

